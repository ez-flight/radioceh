ADVANCE = 0.8


def text_width(text, h=1.0):
    return len(text) * ADVANCE * h


def strokes(text, x, y, h=1.0, anchor="left"):
    """Ломаные надписи (мм, ось Y вверх); x, y — левый (или центр при anchor='center') нижний край."""
    x0 = x - text_width(text, h) / 2 if anchor == "center" else x
    out = []
    for i, ch in enumerate(text.upper()):
        ch = TR.get(ch, ch)
        for poly in G.get(ch, G["?"]):
            out.append([(x0 + i * ADVANCE * h + px * h, y + py * h) for px, py in poly])
    return out
